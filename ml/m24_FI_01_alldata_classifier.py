#[실습] cancer, wine, digits

import numpy as np
from sklearn.datasets import load_breast_cancer, load_wine, load_digits
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import MinMaxScaler
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier
from xgboost import XGBClassifier

#1. 데이터
datas = [load_breast_cancer, load_wine, load_digits]
name = ['cancer', 'wine', 'digits']

for i, data in enumerate(datas):
    x, y = data(return_X_y=True)
    # print(x.shape, y.shape)

    random_state1=123
    random_state2=1223

    x_train, x_test, y_train, y_test = train_test_split(
        x, y, train_size=0.8, stratify=y, shuffle=True, random_state=123)

    scaler = MinMaxScaler()
    x_train = scaler.fit_transform(x_train)
    x_test = scaler.transform(x_test)

    model1 = DecisionTreeClassifier(random_state=random_state2)
    model2 = RandomForestClassifier(random_state=random_state2)
    model3 = GradientBoostingClassifier(random_state=random_state2)
    model4 = XGBClassifier(random_state=random_state2)

    models = [model1, model2, model3, model4]

    print('##########', name[i], '##########')
    print('random_state :', random_state1, random_state2)
    for model in models:
        model.fit(x_train, y_train)
        print('==========', model.__class__.__name__, '==========')
        print('acc :', model.score(x_test, y_test))
        print(model.feature_importances_)

    print(' ')

